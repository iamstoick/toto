//! Full v1 token set (spec §2.2). The lexer produces every token here,
//! including ones the core parser rejects with phase-naming diagnostics.

use crate::span::Span;

/// A token with its source span.
#[derive(Clone, Debug)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

/// Every terminal in the v1 grammar plus keywords.
#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Colon,
    Semi,
    Dot,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Eq,
    Lt,
    Gt,
    Bang,
    Question,
    At,
    EqEq,
    BangEq,
    LtEq,
    GtEq,
    AndAnd,
    OrOr,
    Arrow,
    FatArrow,
    LtMinus,
    DotDot,
    Int(i64),
    Float(f64),
    Str(String),
    Ident(String),
    /// Doc-comment text with the marker stripped: `outer` is true
    /// for `///` (item doc, attaches to the following item) and
    /// false for `//!` (module doc, valid at file top only). One
    /// optional leading space stripped; trailing `\r` from CRLF
    /// endings trimmed.
    DocComment {
        outer: bool,
        text: String,
    },
    True,
    False,
    Fn,
    Let,
    Mut,
    If,
    Else,
    While,
    For,
    In,
    Return,
    Break,
    Continue,
    Struct,
    Go,
    Chan,
    Select,
    Defer,
    Close,
    Unsafe,
    Extern,
    Match,
    Import,
    Mod,
    Use,
    Pub,
    Trait,
    Impl,
    Const,
    Static,
    As,
    Loop,
    SelfKw,
    IntTy,
    FloatTy,
    StringTy,
    BoolTy,
    UnitTy,
    ArrayTy,
    MapTy,
    RangeTy,
    ResultTy,
    OptionTy,
    Some,
    None,
    Ok,
    Err,
    Eof,
}

impl TokenKind {
    /// Short printable name used in diagnostics.
    pub fn name(&self) -> &'static str {
        match self {
            TokenKind::LParen => "`(`",
            TokenKind::RParen => "`)`",
            TokenKind::LBrace => "`{`",
            TokenKind::RBrace => "`}`",
            TokenKind::LBracket => "`[`",
            TokenKind::RBracket => "`]`",
            TokenKind::Comma => "`,`",
            TokenKind::Colon => "`:`",
            TokenKind::Semi => "`;`",
            TokenKind::Dot => "`.`",
            TokenKind::Plus => "`+`",
            TokenKind::Minus => "`-`",
            TokenKind::Star => "`*`",
            TokenKind::Slash => "`/`",
            TokenKind::Percent => "`%`",
            TokenKind::Eq => "`=`",
            TokenKind::Lt => "`<`",
            TokenKind::Gt => "`>`",
            TokenKind::Bang => "`!`",
            TokenKind::Question => "`?`",
            TokenKind::At => "`@`",
            TokenKind::EqEq => "`==`",
            TokenKind::BangEq => "`!=`",
            TokenKind::LtEq => "`<=`",
            TokenKind::GtEq => "`>=`",
            TokenKind::AndAnd => "`&&`",
            TokenKind::OrOr => "`||`",
            TokenKind::Arrow => "`->`",
            TokenKind::FatArrow => "`=>`",
            TokenKind::LtMinus => "`<-`",
            TokenKind::DotDot => "`..`",
            TokenKind::Int(_) => "integer",
            TokenKind::Float(_) => "float",
            TokenKind::Str(_) => "string",
            TokenKind::Ident(_) => "identifier",
            TokenKind::DocComment { .. } => "doc comment",
            TokenKind::True => "`true`",
            TokenKind::False => "`false`",
            TokenKind::Eof => "end of file",
            other => other.keyword_name(),
        }
    }

    fn keyword_name(&self) -> &'static str {
        match self {
            TokenKind::Fn => "`fn`",
            TokenKind::Let => "`let`",
            TokenKind::Mut => "`mut`",
            TokenKind::If => "`if`",
            TokenKind::Else => "`else`",
            TokenKind::While => "`while`",
            TokenKind::For => "`for`",
            TokenKind::In => "`in`",
            TokenKind::Return => "`return`",
            TokenKind::Break => "`break`",
            TokenKind::Continue => "`continue`",
            TokenKind::Struct => "`struct`",
            TokenKind::Go => "`go`",
            TokenKind::Chan => "`chan`",
            TokenKind::Select => "`select`",
            TokenKind::Defer => "`defer`",
            TokenKind::Close => "`close`",
            TokenKind::Unsafe => "`unsafe`",
            TokenKind::Extern => "`extern`",
            TokenKind::Match => "`match`",
            TokenKind::Import => "`import`",
            TokenKind::Mod => "`mod`",
            TokenKind::Use => "`use`",
            TokenKind::Pub => "`pub`",
            TokenKind::Trait => "`trait`",
            TokenKind::Impl => "`impl`",
            TokenKind::Const => "`const`",
            TokenKind::Static => "`static`",
            TokenKind::As => "`as`",
            TokenKind::Loop => "`loop`",
            TokenKind::SelfKw => "`self`",
            TokenKind::IntTy => "`int`",
            TokenKind::FloatTy => "`float`",
            TokenKind::StringTy => "`string`",
            TokenKind::BoolTy => "`bool`",
            TokenKind::UnitTy => "`unit`",
            TokenKind::ArrayTy => "`Array`",
            TokenKind::MapTy => "`Map`",
            TokenKind::RangeTy => "`Range`",
            TokenKind::ResultTy => "`Result`",
            TokenKind::OptionTy => "`Option`",
            TokenKind::Some => "`Some`",
            TokenKind::None => "`None`",
            TokenKind::Ok => "`Ok`",
            TokenKind::Err => "`Err`",
            _ => "token",
        }
    }
}

/// Map an identifier to its keyword token, if it is one.
pub fn keyword(word: &str) -> Option<TokenKind> {
    let kind = match word {
        "true" => TokenKind::True,
        "false" => TokenKind::False,
        "fn" => TokenKind::Fn,
        "let" => TokenKind::Let,
        "mut" => TokenKind::Mut,
        "if" => TokenKind::If,
        "else" => TokenKind::Else,
        "while" => TokenKind::While,
        "for" => TokenKind::For,
        "in" => TokenKind::In,
        "return" => TokenKind::Return,
        "break" => TokenKind::Break,
        "continue" => TokenKind::Continue,
        "struct" => TokenKind::Struct,
        "go" => TokenKind::Go,
        "chan" => TokenKind::Chan,
        "select" => TokenKind::Select,
        "defer" => TokenKind::Defer,
        "close" => TokenKind::Close,
        "unsafe" => TokenKind::Unsafe,
        "extern" => TokenKind::Extern,
        "match" => TokenKind::Match,
        "import" => TokenKind::Import,
        "mod" => TokenKind::Mod,
        "use" => TokenKind::Use,
        "pub" => TokenKind::Pub,
        "trait" => TokenKind::Trait,
        "impl" => TokenKind::Impl,
        "const" => TokenKind::Const,
        "static" => TokenKind::Static,
        "as" => TokenKind::As,
        "loop" => TokenKind::Loop,
        "self" => TokenKind::SelfKw,
        "int" => TokenKind::IntTy,
        "float" => TokenKind::FloatTy,
        "string" => TokenKind::StringTy,
        "bool" => TokenKind::BoolTy,
        "unit" => TokenKind::UnitTy,
        "Array" => TokenKind::ArrayTy,
        "Map" => TokenKind::MapTy,
        "Range" => TokenKind::RangeTy,
        "Result" => TokenKind::ResultTy,
        "Option" => TokenKind::OptionTy,
        "Some" => TokenKind::Some,
        "None" => TokenKind::None,
        "Ok" => TokenKind::Ok,
        "Err" => TokenKind::Err,
        _ => return None,
    };
    Some(kind)
}
